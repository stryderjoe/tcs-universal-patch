"""Catalog every place the code compares a character with a named character, from your own unwrapped exe.

The exe fills 216 "name -> ID" globals from the table at 0x007F1B50 (FUN_00414340); every check of the form
"is this character Ewok / Grievous / ..." reads one of them. Writes Markdown to stdout: per name, the number
of reads and the functions (start addresses found from the compiler's int3 padding) that read it.
usage: python tools/identity_catalog.py <unwrapped exe> > docs/IDENTITY_CHECKS.md
"""
import collections, struct, sys
import capstone, pefile
from capstone.x86 import X86_OP_MEM

TABLE = 0x007F1B50

# what the patch already opens up (function start -> note)
HANDLED = {
    0x00407E40: "projectile picker: `bullet=`",
    0x00414400: "behaviour routines: `behaviour=`",
    0x0041DAD0: "saber draw: `blade_style=`",
    0x0049F850: "blade glow: `blade_style=`",
    0x004A0900: "streak bits: `blade_style=`",
    0x004B4AC0: "weapon always out: `weapon_always_out`",
    0x004BDE10: "rock sounds: preloaded for Ewok bullets",
    0x004DE2A0: "arena picker: `[arena]`",
}


def main(path):
    pe = pefile.PE(path)
    img = pe.get_memory_mapped_image()
    base_va = pe.OPTIONAL_HEADER.ImageBase
    u32 = lambda a: struct.unpack_from("<I", img, a - base_va)[0]
    cstr = lambda a: img[a - base_va:img.find(b"\0", a - base_va)].decode("latin1")
    names, a = {}, TABLE
    while u32(a):
        names[u32(a + 4)] = cstr(u32(a))
        a += 8
    text = pe.sections[0]
    code, base = text.get_data(), base_va + text.VirtualAddress
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
    md.detail, md.skipdata = True, True
    func, pad = base, 0
    reads = collections.defaultdict(lambda: collections.Counter())
    for ins in md.disasm(code, base):
        if ins.id == 0:
            continue
        if ins.mnemonic == "int3":
            pad += 1
            continue
        if pad and ins.address % 16 == 0:
            func = ins.address
        pad = 0
        for op in ins.operands:
            if op.type == X86_OP_MEM and not op.mem.base and not op.mem.index:
                d = op.mem.disp & 0xFFFFFFFF
                if d in names:
                    reads[names[d]][func] += 1
    total = sum(sum(c.values()) for c in reads.values())
    funcs = {f for c in reads.values() for f in c}
    print("# Every check against a named character\n")
    print(f"Generated by `tools/identity_catalog.py` from the unwrapped Steam build. {total} reads of the "
          f"{len(names)} name -> ID globals (table `0x{TABLE:08X}`), in {len(funcs)} functions. A read is "
          "not always a check (some code uses an ID as a value, for example to spawn that character); "
          "functions marked with a note are opened up by this patch.\n")
    print("| Character | Reads | Functions (start address: reads) |")
    print("| --- | --- | --- |")
    for name, c in sorted(reads.items(), key=lambda kv: -sum(kv[1].values())):
        parts = []
        for f, n in sorted(c.items()):
            note = HANDLED.get(f)
            parts.append(f"`{f:08X}`: {n}" + (f" ({note})" if note else ""))
        print(f"| {name} | {sum(c.values())} | " + ", ".join(parts) + " |")
    unread = sorted(n for n in names.values() if n not in reads)
    print(f"\nNever read by code ({len(unread)}): " + ", ".join(unread))


if __name__ == "__main__":
    main(sys.argv[1])
