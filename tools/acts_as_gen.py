"""Generate the table of "is this character <name>?" compares for the `acts_as` keyword.

Lists every `cmp ax|cx|dx, word ptr [<name ID global>]` whose next instruction is je/jne (so only the zero
flag matters), from your own unwrapped exe. Sites the patch already handles in its own way are left out.
usage: python tools/acts_as_gen.py <exe> > src/acts_as_table.h  (addresses and values only, no code)
"""
import struct, sys
import capstone, pefile
from capstone.x86 import X86_OP_MEM, X86_OP_REG

TABLE = 0x007F1B50
REGS = {"ax": 0, "cx": 1, "dx": 2}
SKIP = {0x0041A919, 0x0041C0D3, 0x0041CB0E, 0x00429B8F, 0x004B3D51, 0x004CB2A2,  # geonosian_variant
        0x004B4B35,                                                                # weapon_always_out
        0x004BFDCA, 0x004BFDD5}                                                    # rock-sound preload (both checks)


def main(path):
    pe = pefile.PE(path)
    img = pe.get_memory_mapped_image()
    vb = pe.OPTIONAL_HEADER.ImageBase
    u32 = lambda a: struct.unpack_from("<I", img, a - vb)[0]
    ids, a = {}, TABLE
    while u32(a):
        ids[u32(a + 4)] = img[u32(a) - vb:img.find(b"\0", u32(a) - vb)].decode("latin1")
        a += 8
    text = pe.sections[0]
    code, base = text.get_data(), vb + text.VirtualAddress
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
    md.detail, md.skipdata = True, True
    insns = [i for i in md.disasm(code, base) if i.id]
    rows, skipped = [], 0
    for i, nxt in zip(insns, insns[1:]):
        if i.mnemonic != "cmp" or i.size != 7 or len(i.operands) != 2:
            continue
        r, m = i.operands
        if r.type != X86_OP_REG or m.type != X86_OP_MEM or m.mem.base or m.mem.index:
            continue
        reg, d = md.reg_name(r.reg), m.mem.disp & 0xFFFFFFFF
        if reg not in REGS or d not in ids or i.address in SKIP:
            continue
        if nxt.mnemonic not in ("je", "jne"):
            skipped += 1
            continue
        rows.append((i.address, REGS[reg], d, ids[d]))
    REG32 = {"eax": 0, "ecx": 1, "edx": 2, "ebx": 3, "esp": 4, "ebp": 5, "esi": 6, "edi": 7}
    loads = []   # movsx r32, word [ID]; cmp rA, r32 (either order); je/jne
    for i, n1, n2 in zip(insns, insns[1:], insns[2:]):
        if i.mnemonic != "movsx" or i.size != 7 or len(i.operands) != 2 or n1.size != 2 or i.address in SKIP:
            continue
        dreg, m = i.operands
        if m.type != X86_OP_MEM or m.mem.base or m.mem.index or (m.mem.disp & 0xFFFFFFFF) not in ids:
            continue
        if n1.mnemonic != "cmp" or n2.mnemonic not in ("je", "jne") or len(n1.operands) != 2:
            continue
        regs = [md.reg_name(o.reg) for o in n1.operands if o.type == X86_OP_REG]
        dst = md.reg_name(dreg.reg)
        if len(regs) != 2 or dst not in regs or regs[0] == regs[1]:
            continue
        other = regs[1] if regs[0] == dst else regs[0]
        if other not in REG32 or other == "esp":
            continue
        loads.append((i.address, REG32[other], m.mem.disp & 0xFFFFFFFF))
    print("/* generated by tools/acts_as_gen.py; addresses and values only */")
    print("typedef struct { unsigned addr; unsigned char reg; unsigned id_global; } ActsAsSite;")
    print("static const ActsAsSite ACTS_AS_SITES[] = {")
    for addr, reg, d, name in rows:
        print(f"    {{ 0x{addr:08X}u, {reg}, 0x{d:08X}u }},  /* {name} */")
    print("};")
    print("typedef struct { unsigned addr; unsigned char other_reg; unsigned id_global; } ActsAsLoad;")
    print("static const ActsAsLoad ACTS_AS_LOADS[] = {")
    for addr, reg, d in loads:
        print(f"    {{ 0x{addr:08X}u, {reg}, 0x{d:08X}u }},  /* {ids[d]} */")
    print("};")
    print(f"/* {len(rows)} sites; {skipped} compares followed by another jump were left out; {len(loads)} load-and-compare sites */")
    print(f"{len(rows)} sites, {skipped} left out, {len(loads)} load-and-compare", file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv[1])
