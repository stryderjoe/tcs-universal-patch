"""Generate the relocation table for a larger party, from your own unwrapped LEGOStarWarsSaga.exe.

Every 4-byte address field (displacement or immediate) that points into one of the party regions below is
listed with the byte offset of the field inside its instruction and the value it holds. The patch rewrites
each field to the same position in a larger buffer, after checking the old value is still there.
Writes C to stdout: `python tools/party_reloc_gen.py <exe> > src/party_table.h`.
The output holds only addresses and numbers from your exe, no code.
"""
import collections, sys
import capstone, pefile
from capstone.x86 import X86_OP_IMM, X86_OP_MEM

# name, start, stride, stock slots, end (exclusive) of what is moved
REGIONS = [
    ("PARTY_PTRS",  0x0093D7F0, 4,    8, 0x0093D818),  # 8 slots + two special pointers (0x93D810, 0x93D814)
    ("SLOT_10",     0x0093D510, 0x10, 8, 0x0093D590),
    ("FREEPLAY",    0x0093D590, 2,    8, 0x0093D5A0),
    ("SLOT_10B",    0x0093D5A0, 0x10, 8, 0x0093D620),
    ("SLOT_38",     0x0093D630, 0x38, 8, 0x0093D7F0),
    ("SLOT_B4",     0x00854898, 0xB4, 8, 0x00854898 + 8 * 0xB4),
    ("LEVEL_PAIRS", 0x00951258, 4,   10, 0x00951280),
    ("LEVEL_IDS",   0x0095107C, 2,   10, 0x00951090),
    ("SLOT_BYTES",  0x00881258, 1,    8, 0x00881260),  # filled from +0xCC4, padded to 8
    ("SLOT_FLOATS", 0x00876C98, 4,    8, 0x00876CB8),  # written by slot in FUN_0043E530
    ("UNLOCKS",     0x0087A18E, 2,    9, 0x0087A1A0),  # level-end unlock list (read as entry i-1 too)
    ("SAVED_CBC",   0x00855E84, 4,    8, 0x00855EA4),  # +0xCBC of each member, saved between areas
    ("ATTACKERS",   0x00876858, 0x88, 8, 0x00876C98),  # up to 17 attackers per member (FUN_0043D450)
]


def region_of(v):
    for k, (name, start, stride, slots, end) in enumerate(REGIONS):
        if start <= v < end:
            return k
    return None


def scan(path):
    pe = pefile.PE(path)
    text = pe.sections[0]
    code, base = text.get_data(), pe.OPTIONAL_HEADER.ImageBase + text.VirtualAddress
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
    md.detail, md.skipdata = True, True
    out = []
    for ins in md.disasm(code, base):
        if ins.id == 0:
            continue
        for op in ins.operands:
            if op.type == X86_OP_MEM and ins.disp_size == 4:
                v, off, kind = op.mem.disp & 0xFFFFFFFF, ins.disp_offset, "mem"
            elif op.type == X86_OP_IMM and ins.imm_size == 4:
                v, off, kind = op.imm & 0xFFFFFFFF, ins.imm_offset, "imm"
            else:
                continue
            k = region_of(v)
            if k is not None:
                out.append((ins.address, off, v, k, kind, f"{ins.mnemonic} {ins.op_str}"))
    return out


def main(path):
    rows = scan(path)
    count = collections.Counter(REGIONS[r[3]][0] for r in rows)
    print("/* generated by tools/party_reloc_gen.py; addresses and values only */")
    print("typedef struct { unsigned addr; unsigned char offset, region; unsigned old; } PartyReloc;")
    print("static const struct { unsigned start, stride, slots, end; } PARTY_REGIONS[] = {")
    for name, start, stride, slots, end in REGIONS:
        print(f"    {{ 0x{start:08X}u, 0x{stride:X}, {slots}, 0x{end:08X}u }},  /* {name} */")
    print("};")
    print("static const PartyReloc PARTY_RELOCS[] = {")
    for addr, off, v, k, kind, text in sorted(set(rows)):
        print(f"    {{ 0x{addr:08X}u, {off}, {k}, 0x{v:08X}u }},")
    print("};")
    print(f"/* {len(rows)} fields: " + ", ".join(f"{n} {c}" for n, c in count.items()) + " */")
    print(", ".join(f"{n} {c}" for n, c in count.items()), file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv[1])
